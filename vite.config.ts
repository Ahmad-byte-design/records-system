import { createHash } from 'node:crypto';
import { readdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, URL } from 'node:url';
import tailwindcss from '@tailwindcss/vite';
import react from '@vitejs/plugin-react';
import { defineConfig, type Plugin } from 'vite';

/**
 * Adds offline support without a runtime dependency: after every production
 * build the plugin fingerprints the emitted files and writes `dist/sw.js`
 * with that exact list. The service worker therefore precaches the whole app
 * shell, including hashed chunks, and can boot the app with no network.
 */
function offlinePlugin(): Plugin {
  let outDir = '';

  const listFiles = async (directory: string): Promise<string[]> => {
    const entries = await readdir(directory, { withFileTypes: true });
    const nested = await Promise.all(
      entries.map((entry) =>
        entry.isDirectory()
          ? listFiles(path.join(directory, entry.name))
          : Promise.resolve([path.join(directory, entry.name)]),
      ),
    );
    return nested.flat();
  };

  return {
    name: 'nour-offline',
    apply: 'build',
    configResolved(config) {
      outDir = path.resolve(config.root, config.build.outDir);
    },
    async closeBundle() {
      const files = (await listFiles(outDir)).sort();
      const urls: string[] = [];
      const fingerprints: string[] = [];

      for (const file of files) {
        const relative = path.relative(outDir, file).split(path.sep).join('/');
        if (relative === 'sw.js' || relative.endsWith('.map')) continue;
        const info = await stat(file);
        urls.push(`/${relative}`);
        fingerprints.push(`${relative}:${info.size}`);
      }

      const template = serviceWorker('__VERSION__', urls);
      // Template + fingerprints: any change to the worker or the emitted files
      // produces a new cache name, so clients never mix builds.
      const version = createHash('sha256')
        .update(`${fingerprints.join('|')}|${template}`)
        .digest('hex')
        .slice(0, 12);

      await writeFile(path.join(outDir, 'sw.js'), serviceWorker(version, urls), 'utf8');
    },
  };
}

function serviceWorker(version: string, precache: string[]): string {
  return `/* Generated by vite.config.ts — do not edit by hand. */
const VERSION = '${version}';
const SHELL = '/index.html';
const PRECACHE = 'nour-shell-' + VERSION;
const FONTS = 'nour-fonts-v1';
const PRECACHE_URLS = ${JSON.stringify(precache)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(PRECACHE);
      await cache.addAll(PRECACHE_URLS.map((url) => new Request(url, { cache: 'reload' })));
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(
        keys
          .filter((key) => key.startsWith('nour-') && key !== PRECACHE && key !== FONTS)
          .map((key) => caches.delete(key)),
      );
      await self.clients.claim();
    })(),
  );
});

async function cacheFirst(request) {
  // Vite preview and some hosts send "Vary: Origin"; module scripts are CORS
  // requests, so matching on Vary would miss entries precached with addAll().
  const cached = await caches.match(request, { ignoreVary: true });
  if (cached) return cached;
  const response = await fetch(request);
  if (response.ok) {
    const cache = await caches.open(PRECACHE);
    await cache.put(request, response.clone());
  }
  return response;
}

async function navigate(request) {
  try {
    const response = await fetch(request);
    if (response.ok) {
      const cache = await caches.open(PRECACHE);
      await cache.put(SHELL, response.clone());
    }
    return response;
  } catch {
    return (await caches.match(SHELL, { ignoreVary: true })) ?? Response.error();
  }
}

async function staleWhileRevalidate(request, cacheName) {
  const cache = await caches.open(cacheName);
  const cached = await cache.match(request, { ignoreVary: true });
  const network = fetch(request)
    .then(async (response) => {
      if (response.ok || response.type === 'opaque') {
        await cache.put(request, response.clone());
      }
      return response;
    })
    .catch(() => undefined);

  return cached ?? (await network) ?? Response.error();
}

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);

  if (url.origin === self.location.origin) {
    event.respondWith(request.mode === 'navigate' ? navigate(request) : cacheFirst(request));
    return;
  }

  if (url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com') {
    event.respondWith(staleWhileRevalidate(request, FONTS));
  }
});
`;
}

export default defineConfig({
  plugins: [react(), tailwindcss(), offlinePlugin()],
  resolve: {
    alias: {
      '@': fileURLToPath(new URL('./src', import.meta.url)),
    },
  },
  build: {
    target: 'es2020',
    rollupOptions: {
      output: {
        manualChunks: {
          react: ['react', 'react-dom'],
        },
      },
    },
  },
});
